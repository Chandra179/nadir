#!/usr/bin/env python3
"""Upgrade the committed synthetic golden set to the schema-v3 candidate pack.

The generated annotations are deliberately marked as synthetic and
non-independent. They make the regression fixture useful for exercising the
multi-judgment contract without creating false production evidence.
"""

from __future__ import annotations

import copy
import hashlib
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
GOLDEN_PATH = ROOT / "test/evaluation/golden.json"
CORPUS_PATHS = [
    "samples/calculus.md",
    "samples/linear-algebra.md",
    "samples/numerical-methods.md",
    "samples/trig-functions.md",
]

# These tags add explicit coverage for intents that cannot be represented by
# Retrieval's five query-type hints without changing production ranking
# behaviour. The canonical relevance labels still come from the fixture.
AMBIGUOUS_IDS = {
    "secant-method-failure-mode",
    "root-method-speed-comparison",
    "matrix-special-types",
    "trig-derivative-link",
    "user-integral-power-exception",
    "user-secants-denominator-risk",
    "user-tan-identity-derivative",
    "linear-algebra-eigen-workflow",
}
NEGATIVE_IDS = {
    "secant-no-derivative",
    "integral-power-rule",
    "integral-power-condition",
    "bisection-vs-secant",
    "root-method-derivative-tradeoff",
    "user-bisection-safety",
}


def manifest_sha256() -> str:
    digest = hashlib.sha256()
    for relative_path in CORPUS_PATHS:
        path = ROOT / relative_path
        digest.update(relative_path.encode("utf-8"))
        digest.update(b"\0")
        digest.update(path.read_bytes())
        digest.update(b"\0")
    return digest.hexdigest()


def judgment(annotator_id: str, query: dict[str, object]) -> dict[str, object]:
    return {
        "annotator_id": annotator_id,
        "relevant": copy.deepcopy(query["relevant"]),
        "distractors": copy.deepcopy(query.get("distractors", [])),
    }


def main() -> None:
    raw = json.loads(GOLDEN_PATH.read_text(encoding="utf-8"))
    queries = raw["queries"]
    if len(queries) != 133:
        raise SystemExit(f"expected the active fixture to contain 133 queries, got {len(queries)}")

    for query in queries:
        tags = set(query.get("tags", []))
        if query["id"] in AMBIGUOUS_IDS:
            tags.add("ambiguous")
        if query["id"] in NEGATIVE_IDS:
            tags.add("negative")
        if tags:
            query["tags"] = sorted(tags)
        else:
            query.pop("tags", None)
        query["judgments"] = [
            judgment("synthetic-pass-a", query),
            judgment("synthetic-pass-b", query),
        ]
        query["adjudication"] = {
            "method": "synthetic consensus of two separately recorded evaluator passes; not human adjudication",
            "reviewer_ids": ["synthetic-pass-a", "synthetic-pass-b"],
        }

    raw["schema_version"] = 3
    raw["metadata"] = {
        "dataset": "expert-authored-synthetic-user-intent-candidate",
        "provenance": (
            "Generated by an expert evaluator over the committed four-document sample corpus; "
            "contains no production user queries or user data."
        ),
        "consent": "not-applicable-no-production-user-data",
        "judgment": (
            "two separately recorded synthetic evaluator passes; "
            "not independent human judgments"
        ),
        "release_gate": False,
        "corpus": {
            "id": "nadir-sample-math-v1",
            "documents": CORPUS_PATHS,
            "document_count": len(CORPUS_PATHS),
            "representative": False,
            "manifest_sha256": manifest_sha256(),
        },
        "privacy_review": {
            "status": "not_applicable_no_production_data",
            "reviewer": "not_applicable",
            "reviewed_at": "2026-09-16T00:00:00Z",
        },
        "annotators": [
            {
                "id": "synthetic-pass-a",
                "role": "expert-authored evaluator simulation",
                "human": False,
                "independent": False,
            },
            {
                "id": "synthetic-pass-b",
                "role": "second evaluator simulation",
                "human": False,
                "independent": False,
            },
        ],
    }
    GOLDEN_PATH.write_text(json.dumps(raw, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {len(queries)} queries to {GOLDEN_PATH}")
    print(f"corpus manifest sha256: {raw['metadata']['corpus']['manifest_sha256']}")


if __name__ == "__main__":
    main()
